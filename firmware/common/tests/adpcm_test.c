int main(void)
{
    /* the Python decoder's samples at these positions (adpcm.decode(adpcm.encode(pcm), 520)) */
    static const uint32_t at[] = {0, 1, 2, 3, 10, 100, 504, 505, 506, 519};
    static const int16_t want[] = {0, 11, 41, 104, 9396, 10843, -4882, -5971, -5982, -9301};
    int16_t pcm[600];
    uint32_t n = 0, got, i;
    int fails = 0;
    adpcm_t a;
    adpcm_begin(&a, vec, sizeof vec, 520);
    while ((got = adpcm_render(&a, pcm + n, 37)) > 0)   /* odd chunks across the block edge */
        n += got;
    if (n != 520) {
        printf("FAIL length %u\n", n);
        fails++;
    }
    for (i = 0; i < sizeof at / sizeof at[0]; i++)
        if (pcm[at[i]] != want[i]) {
            printf("FAIL sample %u: %d, Python %d\n", at[i], pcm[at[i]], want[i]);
            fails++;
        }
    printf(fails ? "adpcm: %d failed\n" : "adpcm: ok\n", fails);
    return fails != 0;
}
