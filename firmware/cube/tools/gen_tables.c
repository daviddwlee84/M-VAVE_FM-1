/* The solver's tables for the firmware: builds them as solve.c does with SOLVE_GEN, and writes them as const arrays
 * (flash) to gen/cube_tables.h, with a bank of random-state scrambles for the moments before the first one is found
 * on the FM-1 (power-on). Deterministic: the same output every time.
 *
 *   cc -std=c99 -O2 -DSOLVE_GEN -o build/cube_gen firmware/cube/tools/gen_tables.c
 *   build/cube_gen firmware/cube/gen/cube_tables.h        (just cube-tables) */
#include <stdio.h>
#include <stdlib.h>
#include "../cube.c"
#include "../solve.c"

#define BANK_N 100
#define BANK_W 24                        /* a length byte, then the moves */

static FILE *out;
static long bytes;

/* n values, braced in rows of `row` and groups of `grp` rows (0: flat) */
static void arr(const char *decl, const void *data, int wide, long n, long row, long grp)
{
    long i;
    fprintf(out, "%s = {", decl);
    for (i = 0; i < n; i++) {
        unsigned v = wide ? ((const uint16_t *)data)[i] : ((const uint8_t *)data)[i];
        if (grp && i % (row * grp) == 0) fprintf(out, "\n{");
        if (row && i % row == 0) fprintf(out, "%s{", grp ? "" : "\n");
        else if (!row && i % 24 == 0) fprintf(out, "\n");
        fprintf(out, "%u,", v);
        if (row && i % row == row - 1) fprintf(out, "},");
        if (grp && i % (row * grp) == row * grp - 1) fprintf(out, "},");
    }
    fprintf(out, "\n};\n");
    bytes += n * (wide ? 2 : 1);
}
#define arr16(d, p, n, r, g) arr(d, p, 1, n, r, g)
#define arr8(d, p, n, r, g) arr(d, p, 0, n, r, g)

int main(int argc, char **argv)
{
    int r = solve_init(), i, j;
    uint32_t rng = 0xC0BE5EEDu;
    static uint8_t bank[BANK_N][BANK_W];
    if (argc < 2) {
        fprintf(stderr, "usage: %s OUT.h\n", argv[0]);
        return 2;
    }
    if (r) {
        fprintf(stderr, "solve_init: %d\n", r);
        return 1;
    }
    for (i = 0; i < BANK_N; i++) {
        uint8_t m[SOLVE_MAX];
        int n = solve_scramble(m, &rng, 21);
        if (n < 0 || n >= BANK_W) {
            fprintf(stderr, "bank %d: length %d\n", i, n);
            return 1;
        }
        bank[i][0] = (uint8_t)n;
        for (j = 0; j < n; j++) bank[i][1 + j] = m[j];
    }
    out = fopen(argv[1], "w");
    if (!out) {
        perror(argv[1]);
        return 1;
    }
    fprintf(out, "/* Generated by firmware/cube/tools/gen_tables.c (just cube-tables): do not edit. GPL-3.0-or-later. */\n");
    fprintf(out, "#pragma once\n#include <stdint.h>\n");
    arr16("static const uint16_t TwistMove[N_TWIST_SYM][18]", &TwistMove[0][0], N_TWIST_SYM * 18, 18, 0);
    arr16("static const uint16_t TwistR2S[N_TWIST]", TwistR2S, N_TWIST, 0, 0);
    arr16("static const uint16_t SliceMove[N_SLICE][18]", &SliceMove[0][0], N_SLICE * 18, 18, 0);
    arr16("static const uint16_t SliceConj[N_SLICE][8]", &SliceConj[0][0], N_SLICE * 8, 8, 0);
    arr16("static const uint16_t SliceR2S[N_SLICE]", SliceR2S, N_SLICE, 0, 0);
    arr16("static const uint16_t SliceMask[N_SLICE]", SliceMask, N_SLICE, 0, 0);
    arr16("static const uint16_t FlipChunk[18][3][16]", &FlipChunk[0][0][0], 18 * 3 * 16, 16, 3);
    arr16("static const uint16_t FlipXor[18]", FlipXor, 18, 0, 0);
    arr8("static const uint8_t P1Prun[(N_TWIST_SYM * N_SLICE + 1) / 2]", P1Prun, (long)sizeof P1Prun, 0, 0);
    arr8("static const uint8_t FSPrun[N_SLICE_SYM * N_FLIP / 2]", FSPrun, (long)sizeof FSPrun, 0, 0);
    arr16("static const uint16_t CPermMove[N_PERM_SYM][N_P2]", &CPermMove[0][0], N_PERM_SYM * N_P2, N_P2, 0);
    arr16("static const uint16_t EPermMove[N_PERM_SYM][N_P2]", &EPermMove[0][0], N_PERM_SYM * N_P2, N_P2, 0);
    arr16("static const uint16_t CPermS2R[N_PERM_SYM]", CPermS2R, N_PERM_SYM, 0, 0);
    arr16("static const uint16_t EPermS2R[N_PERM_SYM]", EPermS2R, N_PERM_SYM, 0, 0);
    arr8("static const uint8_t MPermMove[N_MPERM][N_P2]", &MPermMove[0][0], N_MPERM * N_P2, N_P2, 0);
    arr8("static const uint8_t MPermConj[N_MPERM][16]", &MPermConj[0][0], N_MPERM * 16, 16, 0);
    arr8("static const uint8_t MCPrun[N_PERM_SYM * N_MPERM / 2]", MCPrun, (long)sizeof MCPrun, 0, 0);
    arr8("static const uint8_t MEPrun[N_PERM_SYM * N_MPERM / 2]", MEPrun, (long)sizeof MEPrun, 0, 0);
    fprintf(out, "#define SOLVE_BANK_N %d\n#define SOLVE_BANK_W %d\n", BANK_N, BANK_W);
    arr8("static const uint8_t SOLVE_BANK[SOLVE_BANK_N][SOLVE_BANK_W]", &bank[0][0], BANK_N * BANK_W, BANK_W, 0);
    fclose(out);
    printf("%s: %ld bytes of tables\n", argv[1], bytes);
    return 0;
}
