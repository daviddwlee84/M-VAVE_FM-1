"""Reference spellings from music21 for firmware/theory's unit tests.

Writes firmware/theory/tests/vectors.h: scales on 18 tonics, key signatures, chord symbols on 21 roots, interval
names and Roman numerals in the 15 major keys, all spelled by music21 (BSD-3-Clause), so theory.c is checked
against an implementation it did not come from. The file is committed; the tests need no network.

    just theory-vectors     (uv run --with music21==10.5.2 python -I host/theory/make_vectors.py)

Ours differs from music21 by design in one place: the 13th chord leaves out the 11th.

Left out on purpose: pentatonic and blues scales (no music21 class; tests/theory_test.c has them by hand), and
Roman numerals in minor keys (music21 reads VI and VII against the minor scale, theory.c against the major
scale on the same tonic, the pop habit: see theory.h).
"""

import sys
from pathlib import Path

import music21
from music21 import harmony, interval, key, pitch, roman, scale

OUT = Path(__file__).resolve().parents[2] / "firmware" / "theory" / "tests" / "vectors.h"

TONICS = ["Cb", "Gb", "Db", "Ab", "Eb", "Bb", "F", "C", "G", "D", "A", "E", "B", "F#", "C#", "G#", "D#", "A#"]
MAJOR_KEYS = TONICS[:15]
MINOR_KEYS = TONICS[3:]
ROOTS = [letter + acc for letter in "CDEFGAB" for acc in ("", "#", "b")]

SCALES = {  # theory.c's th_scales[].name -> music21 class
    "major": scale.MajorScale,
    "dorian": scale.DorianScale,
    "phrygian": scale.PhrygianScale,
    "lydian": scale.LydianScale,
    "mixolydian": scale.MixolydianScale,
    "minor": scale.MinorScale,
    "locrian": scale.LocrianScale,
    "harmonic minor": scale.HarmonicMinorScale,
    "melodic minor": scale.MelodicMinorScale,
}

CHORDS = {  # theory.c's chord symbol -> music21's
    "": "", "m": "m", "dim": "dim", "aug": "+", "sus4": "sus4", "sus2": "sus2",
    "7": "7", "maj7": "maj7", "m7": "m7", "m7b5": "ø7", "dim7": "o7", "m(maj7)": "mM7", "6": "6", "m6": "m6",
    "7sus4": "7sus4", "add9": "add9", "m(add9)": "madd9", "9": "9", "maj9": "M9", "m9": "m9",
    "7#5": "+7", "maj7#5": "+M7", "6/9": "6add9", "7b9": "7b9", "7#9": "7#9", "13": "13", "5": "power",
}
NO_11 = {"13"}  # music21's 13th has the 11th; ours leaves it out, as voicings usually do

# Roman numerals the two read the same way (music21's 7 is the key's own seventh, so bVII7 is left out).
NUMERALS = ["I", "ii", "iii", "IV", "V", "vi", "viio", "IM7", "ii7", "iii7", "IVM7", "V7", "vi7", "vii/o7",
            "viio7", "V9", "V7/V", "V/V", "V7/vi", "V/ii", "V7/ii", "V7/iii", "V7/IV", "viio7/V", "bVII", "bVI",
            "bIII", "bII", "iv", "I+"]


def m21(name: str) -> str:
    """Our spelling to music21's (flats are '-')."""
    return name[0] + name[1:].replace("b", "-")


def ours(p: pitch.Pitch) -> str:
    return p.name.replace("-", "b")


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    lines = [
        "/* Generated by host/theory/make_vectors.py from music21 " + music21.VERSION_STR + ". Do not edit. */",
        "/* SPDX-License-Identifier: GPL-3.0-or-later */",
        "",
        "static const struct { const char *tonic, *scale, *notes; } VEC_SCALES[] = {",
    ]
    for name, cls in SCALES.items():
        for t in TONICS:
            sc = cls(m21(t))
            kw = {"direction": scale.Direction.ASCENDING} if cls is scale.MelodicMinorScale else {}
            notes = [ours(p) for p in sc.getPitches(m21(t) + "4", m21(t) + "5", **kw)][:7]
            lines.append(f"    {{ {c_str(t)}, {c_str(name)}, {c_str(' '.join(notes))} }},")
    lines += ["};", "", "static const struct { const char *tonic; int minor, sharps; } VEC_KEYSIGS[] = {"]
    for t in MAJOR_KEYS:
        lines.append(f"    {{ {c_str(t)}, 0, {key.Key(m21(t)).sharps} }},")
    for t in MINOR_KEYS:
        lines.append(f"    {{ {c_str(t)}, 1, {key.Key(m21(t).lower()).sharps} }},")
    lines += ["};", "", "static const struct { const char *root, *sym, *notes; } VEC_CHORDS[] = {"]
    for sym, fig in CHORDS.items():
        for r in ROOTS:
            cs = harmony.ChordSymbol(m21(r) + fig)
            root = cs.root()
            pitches = [p for p in cs.pitches
                       if not (sym in NO_11 and interval.Interval(root, p).simpleName == "P4")]
            notes = " ".join(ours(p) for p in pitches)
            lines.append(f"    {{ {c_str(r)}, {c_str(sym)}, {c_str(notes)} }},")
    lines += ["};", "", "static const struct { const char *note, *name; } VEC_INTERVALS[] = {"]
    for letter in "CDEFGAB":
        for acc in ("bb", "b", "", "#", "##"):
            n = letter + acc
            iv = interval.Interval(pitch.Pitch("C4"), pitch.Pitch(m21(n) + "4"))
            lines.append(f"    {{ {c_str(n)}, {c_str(iv.simpleName)} }},")
    lines += ["};", "", "static const struct { const char *key, *rn, *notes; } VEC_ROMAN[] = {"]
    for t in MAJOR_KEYS:
        for rn in NUMERALS:
            r = roman.RomanNumeral(rn, key.Key(m21(t)))
            notes = " ".join(ours(p) for p in r.pitches)
            lines.append(f"    {{ {c_str(t)}, {c_str(rn)}, {c_str(notes)} }},")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(lines)} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
