"""firmware/voicelab/gen/voicedata.h: the single test words (one a key, at most 27) as the firmware plays them, the
LPC stream (25 ms frames) and IMA ADPCM at 11025 Hz, from the lab's renderings. Git-ignored: made from macOS `say`.
"""

from __future__ import annotations

from pathlib import Path

from . import adpcm, lab, wav

OUT_H = lab.ROOT / "firmware/voicelab/gen/voicedata.h"
NKEYS = 27


def _array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def write(path: Path = OUT_H) -> None:
    words = [w for w in lab.load_words() if " " not in w][:NKEYS]
    parts, table = [], []
    total_lpc = total_adp = 0
    for i, w in enumerate(words):
        sl = lab.slug(w)
        lpc_bin = lab.TMP / f"{sl}-25.lpc"
        src = lab.TMP / f"{sl}-11025.wav"
        if not lpc_bin.exists():
            lab.r_lpc(w, lab.OUT / "lpc25" / f"{sl}.wav", 25)
        if not src.exists():
            lab.r_adpcm(w, lab.OUT / "adpcm11" / f"{sl}.wav", 11025)
        lpc = lpc_bin.read_bytes()
        pcm, rate = wav.read(src)
        assert rate == 11025
        adp = adpcm.encode(pcm)
        total_lpc += len(lpc)
        total_adp += len(adp)
        parts += [_array(f"vl_lpc_{i}", lpc), _array(f"vl_adp_{i}", adp)]
        table.append(f'    {{"{w}", vl_lpc_{i}, {len(lpc)}u, vl_adp_{i}, {len(adp)}u, {len(pcm)}u}},')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "/* generated by host/voicelab/fwdata.py (just voice-fw) from build/voicelab: do not edit, do not commit */\n"
        f"/* {len(words)} words: LPC {total_lpc} bytes, ADPCM {total_adp} bytes */\n"
        f"#define VL_N {len(words)}u\n" + "".join(parts) +
        f"static const vl_word_t vl_words[VL_N] = {{\n" + "\n".join(table) + "\n};\n")
    print(f"{path.relative_to(lab.ROOT)}: {len(words)} words, LPC {total_lpc} B, ADPCM {total_adp} B")
