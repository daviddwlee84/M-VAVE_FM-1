"""Reference vectors for CUBE's cube model: firmware/cube/tests/vectors.h (just cube-vectors).

Reads "scramble<TAB>facelets" lines (firmware/cube/tests/cube_dump.c) on stdin and asks Herbert Kociemba's own
two-phase solver (the `kociemba` package) to solve each sticker string. cube_test.c then checks that cube.c makes the
same stickers from the scramble and that Kociemba's solution solves them: an outside check of our move and sticker
conventions. Only the output (data) goes into the repository.
"""
import sys

import kociemba


def main() -> None:
    rows = []
    for line in sys.stdin:
        line = line.rstrip("\n")
        if not line:
            continue
        scramble, facelets = line.split("\t")
        rows.append((scramble, facelets, kociemba.solve(facelets)))
    print("/* Generated by host/cube/make_vectors.py (just cube-vectors) with the kociemba package: do not edit. */")
    print("#pragma once")
    print("static const struct {\n    const char *scramble, *facelets, *solution;\n} CUBE_VEC[] = {")
    for s, f, k in rows:
        print(f'    {{"{s}", "{f}", "{k}"}},')
    print("};")


if __name__ == "__main__":
    main()
